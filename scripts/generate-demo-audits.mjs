#!/usr/bin/env node
/**
 * generate-demo-audits.mjs
 *
 * Reads the real segment geometry from `data/segments.geojson` and paints a
 * SIMULATED field campaign over it. Nothing here is a measurement. Every record
 * is marked `demo: true` and the audits file carries `simulated: true` plus an
 * explicit honesty note, because the demo dataset must never read as completed
 * real fieldwork.
 *
 * DIRECTION OF THE MODEL (this changed in bgsd-0018; read before editing).
 * The generator used to invent a lens score from geography and then derive
 * plausible per-item answers from it, which meant the published score and the
 * observations under it did not agree: a segment could show 74 accessibility
 * over answers that roll up to something else entirely. It now runs the only
 * way that survives a stakeholder clicking into a segment:
 *
 *     geography + road class  ->  per-item RAW responses  ->  lens scores
 *
 * The rollup is `lensScoresFromItems` from `lib/capture/scoring.ts`, mirrored
 * here in plain JS (normalize by response type, mean per lens, overall =
 * 0.45*accessibility + 0.30*drainage + 0.25*shade, bike stands alone). The two
 * implementations are pinned together by `scripts/test-demo-audits.mjs`, which
 * compiles the real TypeScript rollup and re-derives every published score from
 * the published observations.
 *
 * CALIBRATION. The targets are Costa Rican urban reality, not a flattering
 * demo: near-hostile for cyclists, poor for pedestrians, mediocre drainage,
 * genuinely variable canopy. See `scripts/test-demo-audits.mjs` for the bands
 * this file is held to.
 *
 * DETERMINISM. Every random draw comes from a stream seeded off SEED plus a
 * stable key (the segment id, the item key), so re-running produces a
 * byte-identical file and adding a segment does not reshuffle its neighbours.
 * The seed is recorded in the header block of `data/demo-audits.json`.
 * `--check` regenerates in memory and diffs against what is committed, which is
 * how the test proves the JSON was not hand-edited.
 *
 * Only the San Antonio pilot (esc-sa-*) is scored: it is the audited ground
 * truth. The rest of the canton (esc-ce-*, esc-ce / esc-sr-*) has no fieldwork,
 * so those segments are emitted UNSCORED as `source: "import"` records that the
 * map renders with the neutral community casing (never a score color).
 *
 * Writes:
 *   data/demo-segments.geojson       scored PILOT collection (fallback adapter + map)
 *   data/demo-audits.json            per-segment audit + observation detail (getSegmentDetail)
 *   data/canton-import-segments.json unscored canton segments (neutral map casing)
 *   supabase/seed.sql                rubric v0.1 + pilot geography + demo audits/observations
 *
 * Usage:
 *   node scripts/generate-demo-audits.mjs            regenerate every artifact
 *   node scripts/generate-demo-audits.mjs --check    verify the committed files match
 */

