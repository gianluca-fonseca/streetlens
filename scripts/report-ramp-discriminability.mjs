#!/usr/bin/env node
/*
 * report-ramp-discriminability.mjs — emit the measured evidence table for the
 * score ramps. Not a test (npm test only picks up `test-*.mjs`); this is the
 * document generator behind <EVIDENCE>/ramp-discriminability.md.
 *
 * Two tables, because "the quartiles" means two different things and only
 * reporting one of them would flatter the result:
 *
 *   1. RAMP quartiles — scores 0/25/50/75/100. This measures the ENCODING: how
 *      well the ramp resolves the range it is defined over.
 *   2. DATA quartiles — the actual 25th/50th/75th percentile of the demo
 *      dataset, per lens. This measures what a viewer will really see, which is
 *      a different and much harsher number wherever the scores are bunched.
 *
 * Usage: node scripts/report-ramp-discriminability.mjs > out.md
 */

import { readFileSync } from "node:fs";
import {
  contrast,
  deltaE,
  hexToOklch,
  relativeLuminance,
  sampleRampStops,
  simulateCvd,
} from "./lib/color-lab.mjs";

const ROOT = new URL("..", import.meta.url).pathname;
const src = readFileSync(`${ROOT}components/mapConfig.ts`, "utf8");

function parseStops(block) {
  return [
    ...block.matchAll(/\{\s*at:\s*(\d+),\s*hex:\s*"(#[0-9A-Fa-f]{6})"\s*\}/g),
  ].map((s) => ({ at: Number(s[1]), hex: s[2] }));
}

const RAMP = (() => {
  const block = src.slice(src.indexOf("export const RAMP"), src.indexOf("Width channel"));
  const out = {};
  const heads = [...block.matchAll(/^  (\w+): \{$/gm)];
  heads.forEach((m, i) => {
    const body = block.slice(m.index, heads[i + 1]?.index ?? block.length);
    out[m[1]] = {
      light: parseStops(body.slice(body.indexOf("light: ["), body.indexOf("dark: ["))),
      dark: parseStops(body.slice(body.indexOf("dark: ["))),
    };
  });
  return out;
})();

const WIDTH_AT_0 = Number(/const WIDTH_AT_0 = ([\d.]+);/.exec(src)[1]);
const WIDTH_AT_100 = Number(/const WIDTH_AT_100 = ([\d.]+);/.exec(src)[1]);
const widthFor = (v) => WIDTH_AT_0 + (WIDTH_AT_100 - WIDTH_AT_0) * (v / 100);

/* The rev-7 table, so the "before" column is a measurement and not a memory. */
const REV7 = {
  overall: ["#F45E53", "#CE4D02", "#056E48"],
  accessibility: ["#CE63E9", "#A844EA", "#7629F1"],
  drainage: ["#0E9EAF", "#077FA8", "#0263A8"],
  shade: ["#729D0D", "#148918", "#07703F"],
  bike: ["#EF599A", "#DF1194", "#B20795"],
};
/** Rev 7 sampled in raw sRGB, which is what it shipped. */
function rev7Sample(layer, v) {
  const stops = REV7[layer].map((hex, i) => ({ at: i * 50, hex }));
  const val = Math.max(0, Math.min(100, v));
  let lo = stops[0];
  let hi = stops[stops.length - 1];
  for (let i = 1; i < stops.length; i++) {
    if (val <= stops[i].at) {
      lo = stops[i - 1];
      hi = stops[i];
      break;
    }
  }
  const t = (val - lo.at) / (hi.at - lo.at || 1);
  const rgb = (h) => [
    parseInt(h.slice(1, 3), 16),
    parseInt(h.slice(3, 5), 16),
    parseInt(h.slice(5, 7), 16),
  ];
  const a = rgb(lo.hex);
  const b = rgb(hi.hex);
  return (
    "#" +
    a
      .map((c, i) =>
        Math.round(c + (b[i] - c) * t)
          .toString(16)
          .padStart(2, "0"),
      )
      .join("")
  );
}

const SURFACES = {
  light: { land: "#fafafa", road: "#ffffff" },
  dark: { land: "#0a0a0a", road: "#141414" },
};
const LAYERS = Object.keys(RAMP);
const THEMES = ["light", "dark"];

/** Actual demo-data percentiles, so the report says what a viewer will see. */
function dataPercentiles() {
  const geo = JSON.parse(readFileSync(`${ROOT}data/demo-segments.geojson`, "utf8"));
  const out = {};
  for (const layer of LAYERS) {
    const v = geo.features
      .map((f) => f.properties[`score_${layer}`])
      .filter((x) => typeof x === "number")
      .sort((a, b) => a - b);
    const q = (p) => v[Math.floor((v.length - 1) * p)];
    out[layer] = { n: v.length, p25: q(0.25), p50: q(0.5), p75: q(0.75), min: v[0], max: v[v.length - 1] };
  }
  return out;
}

const dE = (a, b) => ({
  normal: deltaE(a, b),
  deutan: deltaE(simulateCvd(a, "deutan"), simulateCvd(b, "deutan")),
  protan: deltaE(simulateCvd(a, "protan"), simulateCvd(b, "protan")),
});
const fmt = (d) => `${d.normal.toFixed(1)} / ${d.deutan.toFixed(1)} / ${d.protan.toFixed(1)}`;

const L = console.log;

L("# Ramp discriminability — rev 8 vs rev 7");
L("");
L("Generated by `node scripts/report-ramp-discriminability.mjs`. Every number is");
L("measured, none is asserted. ΔE is Euclidean distance in OKLab ×100 (the unit");
L("the dataviz skill's validator uses). CVD columns are Machado, Oliveira &");
L("Fernandes 2009 at severity 1.0 (full dichromacy), applied in linear RGB.");
L("");
L("**Threshold, and why.** Adjacent quartiles must clear ΔE 8 under normal vision");
L("— the dataviz skill's categorical target, the distance at which two colours");
L("reliably read as two colours rather than as a shade of one. Under simulated");
L("dichromacy they must clear its 6 floor, which the skill permits only alongside");
L("secondary encoding; that encoding genuinely ships here (line width, the hero's");
L("extrusion height, the binned legend). The pair that decides the product is the");
L("25th vs the 75th percentile, so it is held to 15 normal and 12 simulated. A");
L("ramp whose adjacent quartiles sit under a just-noticeable difference at line");
L("widths has failed, which is exactly what rev 7 did.");
L("");
L("## 1. The encoding: ramp quartiles (scores 0/25/50/75/100)");
L("");
L("ΔE columns are `normal / deuteranopia / protanopia`.");
L("");

for (const theme of THEMES) {
  L(`### ${theme} basemap (land ${SURFACES[theme].land}, road ${SURFACES[theme].road})`);
  L("");
  L("| lens | stop | hex | OKLCH L | contrast vs land | vs road | width px |");
  L("|---|---|---|---|---|---|---|");
  for (const layer of LAYERS) {
    for (const s of RAMP[layer][theme]) {
      const [l] = hexToOklch(s.hex);
      L(
        `| ${layer} | ${s.at} | \`${s.hex}\` | ${l.toFixed(3)} | ` +
          `${contrast(s.hex, SURFACES[theme].land).toFixed(2)}:1 | ` +
          `${contrast(s.hex, SURFACES[theme].road).toFixed(2)}:1 | ` +
          `${widthFor(s.at).toFixed(1)} |`,
      );
    }
  }
  L("");
  L("| lens | 0→25 | 25→50 | 50→75 | 75→100 | **25↔75** | 0↔100 |");
  L("|---|---|---|---|---|---|---|");
  for (const layer of LAYERS) {
    const stops = RAMP[layer][theme];
    const at = (v) => sampleRampStops(stops, v);
    const cells = [];
    for (const [a, b] of [[0, 25], [25, 50], [50, 75], [75, 100]]) {
      cells.push(fmt(dE(at(a), at(b))));
    }
    L(
      `| ${layer} | ${cells.join(" | ")} | **${fmt(dE(at(25), at(75)))}** | ` +
        `${fmt(dE(at(0), at(100)))} |`,
    );
  }
  L("");
}

L("## 2. Rev 7 for comparison, measured the same way");
L("");
L("Rev 7 shipped ONE table for both basemaps and interpolated it in raw sRGB.");
L("");
L("| lens | 0→25 | 25→50 | 50→75 | 75→100 | **25↔75** | 0↔100 |");
L("|---|---|---|---|---|---|---|");
for (const layer of LAYERS) {
  const at = (v) => rev7Sample(layer, v);
  const cells = [];
  for (const [a, b] of [[0, 25], [25, 50], [50, 75], [75, 100]]) {
    cells.push(fmt(dE(at(a), at(b))));
  }
  L(
    `| ${layer} | ${cells.join(" | ")} | **${fmt(dE(at(25), at(75)))}** | ` +
      `${fmt(dE(at(0), at(100)))} |`,
  );
}
L("");

L("## 3. What a viewer actually sees: the demo data's own percentiles");
L("");
L("The encoding resolves 0–100. The demo dataset does not USE 0–100, and where");
L("its scores are bunched no ramp can pull them apart without lying about them.");
L("This table is the honest version of the squint test on the shipped data.");
L("");
const pct = dataPercentiles();
L("| lens | n | min | p25 | p50 | p75 | max | span |");
L("|---|---|---|---|---|---|---|---|");
for (const layer of LAYERS) {
  const p = pct[layer];
  L(
    `| ${layer} | ${p.n} | ${p.min} | ${p.p25} | ${p.p50} | ${p.p75} | ${p.max} | ` +
      `${p.p75 - p.p25} pts |`,
  );
}
L("");
for (const theme of THEMES) {
  L(`### ${theme} basemap, at the data's percentiles`);
  L("");
  L("| lens | p25→p50 | p50→p75 | **p25↔p75** | width p25→p75 |");
  L("|---|---|---|---|---|");
  for (const layer of LAYERS) {
    const stops = RAMP[layer][theme];
    const at = (v) => sampleRampStops(stops, v);
    const p = pct[layer];
    L(
      `| ${layer} | ${fmt(dE(at(p.p25), at(p.p50)))} | ${fmt(dE(at(p.p50), at(p.p75)))} | ` +
        `**${fmt(dE(at(p.p25), at(p.p75)))}** | ` +
        `${widthFor(p.p25).toFixed(1)} → ${widthFor(p.p75).toFixed(1)} px |`,
    );
  }
  L("");
}

L("## 4. Colour-vision simulation: does the ORDER survive?");
L("");
L("Distance is the fine reading. The coarse one is whether worst→best still runs");
L("one way with colour removed. Relative luminance of each stop, simulated:");
L("");
L("| lens | theme | sim | luminance 0 → 100 | monotonic? |");
L("|---|---|---|---|---|");
for (const layer of LAYERS) {
  for (const theme of THEMES) {
    const sign = theme === "light" ? -1 : 1;
    for (const sim of ["none", "deutan", "protan", "tritan"]) {
      const ys = RAMP[layer][theme].map((s) =>
        relativeLuminance(sim === "none" ? s.hex : simulateCvd(s.hex, sim)),
      );
      const ok = ys.every((y, i) => i === 0 || sign * (y - ys[i - 1]) > 0);
      L(
        `| ${layer} | ${theme} | ${sim} | ${ys.map((y) => y.toFixed(3)).join(" → ")} | ` +
          `${ok ? "yes" : "**NO**"} |`,
      );
    }
  }
}
L("");
L("## 5. Lens identity: do two lenses collide at the same score?");
L("");
L("| theme | score | closest pair | ΔE |");
L("|---|---|---|---|");
for (const theme of THEMES) {
  for (const q of [0, 25, 50, 75, 100]) {
    let worst = { d: Infinity, pair: "" };
    for (let i = 0; i < LAYERS.length; i++) {
      for (let j = i + 1; j < LAYERS.length; j++) {
        const a = sampleRampStops(RAMP[LAYERS[i]][theme], q);
        const b = sampleRampStops(RAMP[LAYERS[j]][theme], q);
        const d = deltaE(a, b);
        if (d < worst.d) worst = { d, pair: `${LAYERS[i]} / ${LAYERS[j]}` };
      }
    }
    L(`| ${theme} | ${q} | ${worst.pair} | ${worst.d.toFixed(1)} |`);
  }
}
L("");
